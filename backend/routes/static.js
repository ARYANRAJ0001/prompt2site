const express = require("express");
const mongoose = require("mongoose");
const Project = require("../models/Project");
const { requireAuth } = require("../middleware/auth");
const { startJob } = require("../services/jobs");
const { generateStaticSite } = require("../services/staticGenerator");
const { createRepo, updateRepo } = require("../services/deploy/github");
const { deployZip } = require("../services/deploy/netlify");
const { zipFiles } = require("../services/zip");
const { slug } = require("../services/generator");
const { consume, refund } = require("../services/usage");

const router = express.Router();
router.use(requireAuth);

const userKey = (req) => (typeof req.headers["x-openrouter-key"] === "string" && req.headers["x-openrouter-key"].trim()) || undefined;
const siteFiles = ({ html, css, js }) => ({ "index.html": html || "", "style.css": css || "", "script.js": js || "" });

async function findProject(id, userId) {
  if (!id || !mongoose.isValidObjectId(id)) return null;
  return Project.findOne({ _id: id, userId, type: "static" });
}

// POST /api/static/generate { prompt, theme, imageDataUrl, name }
router.post("/generate", async (req, res, next) => {
  try {
    const prompt = String(req.body.prompt || "").trim();
    if (!prompt) return res.status(400).json({ success: false, message: "Please describe the website you want" });
    const { theme, imageDataUrl } = req.body;
    if (imageDataUrl && !/^data:image\/(png|jpe?g|webp|gif);base64,/.test(imageDataUrl)) {
      return res.status(400).json({ success: false, message: "The image must be PNG, JPG, WEBP or GIF" });
    }
    const name = String(req.body.name || prompt).trim().slice(0, 80);
    const apiKey = userKey(req);
    if (!apiKey) await consume(req.user._id, "ai");

    let job;
    try {
      job = startJob({
      userId: req.user._id,
      type: "Generate website",
      run: async (progress) => {
        const out = await generateStaticSite(prompt, { theme, imageDataUrl, apiKey, onProgress: progress });
        progress("Saving project");
        const project = await Project.create({ userId: req.user._id, type: "static", name, prompt, theme: theme || "", ...out.site });
        return { projectId: String(project._id), site: out.site, source: out.source, warning: out.warning || null };
      },
      });
    } catch (err) {
      if (!apiKey) await refund(req.user._id, "ai");
      throw err;
    }
    res.status(202).json({ success: true, jobId: job.id });
  } catch (err) {
    next(err);
  }
});

// POST /api/static/deploy { projectId, html, css, js, name }
router.post("/deploy", async (req, res, next) => {
  try {
    const project = await findProject(req.body.projectId, req.user._id);
    if (!project) return res.status(404).json({ success: false, message: "Save or generate the website first" });
    const site = { html: req.body.html ?? project.html, css: req.body.css ?? project.css, js: req.body.js ?? project.js };
    if (!String(site.html).trim()) return res.status(400).json({ success: false, message: "The page has no HTML" });
    if (typeof req.body.name === "string" && req.body.name.trim()) project.name = req.body.name.trim().slice(0, 80);
    Object.assign(project, site);
    await project.save();
    await consume(req.user._id, "deploy");

    const job = startJob({
      userId: req.user._id,
      type: "Deploy website",
      run: async (progress) => {
        const files = siteFiles(site);
        let github = "";
        if (process.env.GITHUB_TOKEN) {
          progress("Saving code to GitHub");
          try {
            const repo = project.deploy?.repo
              ? await updateRepo(project.deploy.repo, { ...files, "README.md": `# ${project.name}\n\nStatic website generated by Prompt2Site.\n` })
              : await createRepo(slug(project.name), "Static website generated by Prompt2Site", { ...files, "README.md": `# ${project.name}\n\nStatic website generated by Prompt2Site.\n` });
            project.deploy.repo = { owner: repo.owner, name: repo.name, branch: repo.branch };
            github = repo.url;
          } catch (e) {
            progress(`GitHub skipped: ${e.message}`);
          }
        }

        const zip = await zipFiles(files);
        const deployed = await deployZip(zip, {
          name: slug(project.name),
          siteId: project.deploy?.netlifySiteId,
          fallbackEnv: "NETLIFY_SITE_ID",
          onProgress: progress,
        });

        project.links.live = deployed.url;
        if (github) project.links.github = github;
        project.deploy.netlifySiteId = deployed.siteId;
        project.deploy.deployedAt = new Date();
        project.markModified("deploy");
        await project.save();
        return { live: deployed.url, github: project.links.github || "" };
      },
    });
    res.status(202).json({ success: true, jobId: job.id });
  } catch (err) {
    next(err);
  }
});

// POST /api/static/download { html, css, js, name } -> zip
router.post("/download", async (req, res, next) => {
  try {
    const zip = await zipFiles(siteFiles(req.body));
    res.set({ "Content-Type": "application/zip", "Content-Disposition": `attachment; filename="${slug(req.body.name || "website")}.zip"` });
    res.send(zip);
  } catch (err) {
    next(err);
  }
});

module.exports = router;
