const axios = require("axios");
const { token, describe } = require("./token");

function api() {
  const t = token("GITHUB_TOKEN");
  return axios.create({
    baseURL: "https://api.github.com",
    timeout: 120000,
    headers: {
      Authorization: `Bearer ${t}`,
      Accept: "application/vnd.github+json",
      "X-GitHub-Api-Version": "2022-11-28",
    },
  });
}

function fail(prefix, err) {
  let msg = err.response?.data?.message || err.message;
  if (err.response?.status === 401) msg = `GitHub says "${msg}" — ${describe("GITHUB_TOKEN")}. Make a new classic token with the "repo" box ticked, paste it, and restart the backend`;
  if (err.response?.status === 404 && /create the repository/.test(prefix)) msg += ` — your GITHUB_TOKEN works but isn't allowed to create repositories. Make a classic token with the "repo" box ticked (or a fine-grained token with "All repositories" + Administration: Read and write), then restart the backend`;
  if (err.response?.status === 403 && /not accessible/i.test(msg)) msg += ` — your token can't create repositories. Use a classic token with "repo" ticked`;
  const extra = (err.response?.data?.errors || []).map((e) => e.message || e.code).join(", ");
  return new Error(`${prefix}: ${msg}${extra ? ` (${extra})` : ""}`);
}

/**
 * Commit a whole file map to a branch in one commit.
 * `replace: true` makes the commit contain exactly these files (removes others).
 */
async function commitFiles(gh, owner, repo, branch, files, { message, replace }) {
  let ref;
  for (let i = 0; i < 8 && !ref; i++) {
    try {
      ({ data: ref } = await gh.get(`/repos/${owner}/${repo}/git/ref/heads/${branch}`));
    } catch (e) {
      if (i === 7) throw e;
      await new Promise((r) => setTimeout(r, 1500)); // new repos take a moment
    }
  }
  const parent = ref.object.sha;
  const { data: parentCommit } = await gh.get(`/repos/${owner}/${repo}/git/commits/${parent}`);
  const { data: tree } = await gh.post(`/repos/${owner}/${repo}/git/trees`, {
    ...(replace ? {} : { base_tree: parentCommit.tree.sha }),
    tree: Object.entries(files).map(([path, content]) => ({ path, mode: "100644", type: "blob", content: String(content) })),
  });
  const { data: commit } = await gh.post(`/repos/${owner}/${repo}/git/commits`, { message, tree: tree.sha, parents: [parent] });
  await gh.patch(`/repos/${owner}/${repo}/git/refs/heads/${branch}`, { sha: commit.sha });
  return commit.sha;
}

/** Create a public repo containing `files`. */
async function createRepo(baseName, description, files) {
  const gh = api();
  const name = `${baseName}-${Date.now().toString(36)}`.slice(0, 90);
  let repo;
  try {
    ({ data: repo } = await gh.post("/user/repos", { name, description, private: false, auto_init: true }));
  } catch (err) {
    throw fail("GitHub couldn't create the repository", err);
  }
  const branch = repo.default_branch || "main";
  try {
    await commitFiles(gh, repo.owner.login, repo.name, branch, files, { message: "Generated by Prompt2Site", replace: false });
  } catch (err) {
    throw fail("Uploading files to GitHub failed", err);
  }
  return { url: repo.html_url, owner: repo.owner.login, name: repo.name, branch };
}

/** Replace the contents of an existing repo with `files` (new commit). */
async function updateRepo({ owner, name, branch }, files) {
  const gh = api();
  try {
    await commitFiles(gh, owner, name, branch, files, { message: "Update from Prompt2Site", replace: true });
  } catch (err) {
    throw fail("Updating the GitHub repository failed", err);
  }
  return { url: `https://github.com/${owner}/${name}`, owner, name, branch };
}

/** Delete a repository. Needs a token with the "delete_repo" scope. */
async function deleteRepo({ owner, name }) {
  try {
    await api().delete(`/repos/${owner}/${name}`);
    return { ok: true };
  } catch (err) {
    if (err.response?.status === 404) return { ok: true, note: "already gone" };
    if (err.response?.status === 403) {
      return { ok: false, note: "your GITHUB_TOKEN can't delete repositories (add the delete_repo scope) — delete it on GitHub" };
    }
    return { ok: false, note: err.response?.data?.message || err.message };
  }
}

module.exports = { createRepo, updateRepo, deleteRepo };
